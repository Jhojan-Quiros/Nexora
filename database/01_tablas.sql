-- ---------------------------------------------------------------------
-- DEPARTAMENTO
-- ---------------------------------------------------------------------
CREATE TABLE departamento (
  id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre          VARCHAR2(80)  NOT NULL,
  ubicacion       VARCHAR2(120) NOT NULL,
  activo          CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_departamento        PRIMARY KEY (id_departamento),
  CONSTRAINT uq_departamento_nombre UNIQUE (nombre),
  CONSTRAINT ck_departamento_activo CHECK (activo IN ('S','N'))
);

-- ---------------------------------------------------------------------
-- EMPLEADO
-- ---------------------------------------------------------------------
CREATE TABLE empleado (
  id_empleado     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_departamento NUMBER        NOT NULL,
  nombre_completo VARCHAR2(120) NOT NULL,
  correo          VARCHAR2(120) NOT NULL,
  usuario         VARCHAR2(40)  NOT NULL,
  contrasena_hash VARCHAR2(64)  NOT NULL,
  rol             VARCHAR2(10)  DEFAULT 'EMPLEADO' NOT NULL,
  activo          CHAR(1)       DEFAULT 'S' NOT NULL,
  fecha_registro  DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_empleado          PRIMARY KEY (id_empleado),
  CONSTRAINT fk_empleado_depto    FOREIGN KEY (id_departamento) REFERENCES departamento (id_departamento),
  CONSTRAINT uq_empleado_correo   UNIQUE (correo),
  CONSTRAINT uq_empleado_usuario  UNIQUE (usuario),
  CONSTRAINT ck_empleado_rol      CHECK (rol IN ('ADMIN','TECNICO','EMPLEADO')),
  CONSTRAINT ck_empleado_activo   CHECK (activo IN ('S','N'))
);

-- ---------------------------------------------------------------------
-- TECNICO (especialización 1:1 de EMPLEADO)
-- ---------------------------------------------------------------------
CREATE TABLE tecnico (
  id_tecnico   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empleado  NUMBER       NOT NULL,
  especialidad VARCHAR2(60) NOT NULL,
  nivel        VARCHAR2(10) DEFAULT 'JUNIOR' NOT NULL,
  activo       CHAR(1)      DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_tecnico          PRIMARY KEY (id_tecnico),
  CONSTRAINT fk_tecnico_empleado FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
  CONSTRAINT uq_tecnico_empleado UNIQUE (id_empleado),
  CONSTRAINT ck_tecnico_nivel    CHECK (nivel IN ('JUNIOR','INTERMEDIO','SENIOR')),
  CONSTRAINT ck_tecnico_activo   CHECK (activo IN ('S','N'))
);

-- ---------------------------------------------------------------------
-- EQUIPO
-- ---------------------------------------------------------------------
CREATE TABLE equipo (
  id_equipo    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  tipo         VARCHAR2(20) NOT NULL,
  marca        VARCHAR2(50) NOT NULL,
  modelo       VARCHAR2(60) NOT NULL,
  numero_serie VARCHAR2(60) NOT NULL,
  estado       VARCHAR2(15) DEFAULT 'DISPONIBLE' NOT NULL,
  fecha_compra DATE         NOT NULL,
  CONSTRAINT pk_equipo        PRIMARY KEY (id_equipo),
  CONSTRAINT uq_equipo_serie  UNIQUE (numero_serie),
  CONSTRAINT ck_equipo_tipo   CHECK (tipo IN ('LAPTOP','ESCRITORIO','SERVIDOR','MONITOR',
                                              'IMPRESORA','RED','OTRO')),
  CONSTRAINT ck_equipo_estado CHECK (estado IN ('DISPONIBLE','ASIGNADO','REPARACION','BAJA'))
);

-- ---------------------------------------------------------------------
-- LICENCIA
-- ---------------------------------------------------------------------
CREATE TABLE licencia (
  id_licencia       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  software          VARCHAR2(80)  NOT NULL,
  proveedor         VARCHAR2(80)  NOT NULL,
  clave             VARCHAR2(120) NOT NULL,
  fecha_vencimiento DATE          NOT NULL,
  cantidad          NUMBER(5)     NOT NULL,
  CONSTRAINT pk_licencia          PRIMARY KEY (id_licencia),
  CONSTRAINT uq_licencia_clave    UNIQUE (clave),
  CONSTRAINT ck_licencia_cantidad CHECK (cantidad > 0)
);

-- ---------------------------------------------------------------------
-- ASIGNACION_EQUIPO (historial N:M empleado-equipo)
-- ---------------------------------------------------------------------
CREATE TABLE asignacion_equipo (
  id_asig_equipo NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_equipo      NUMBER NOT NULL,
  id_empleado    NUMBER NOT NULL,
  fecha_inicio   DATE   DEFAULT SYSDATE NOT NULL,
  fecha_fin      DATE,
  CONSTRAINT pk_asignacion_equipo PRIMARY KEY (id_asig_equipo),
  CONSTRAINT fk_asig_eq_equipo    FOREIGN KEY (id_equipo)   REFERENCES equipo (id_equipo),
  CONSTRAINT fk_asig_eq_empleado  FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
  CONSTRAINT ck_asig_eq_fechas    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Un equipo solo puede tener UNA asignación activa (fecha_fin nula)
CREATE UNIQUE INDEX ux_asig_equipo_activa
  ON asignacion_equipo (CASE WHEN fecha_fin IS NULL THEN id_equipo END);

-- ---------------------------------------------------------------------
-- ASIGNACION_LICENCIA (N:M empleado-licencia)
-- ---------------------------------------------------------------------
CREATE TABLE asignacion_licencia (
  id_asig_licencia NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_licencia      NUMBER NOT NULL,
  id_empleado      NUMBER NOT NULL,
  fecha_asignacion DATE   DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_asignacion_licencia PRIMARY KEY (id_asig_licencia),
  CONSTRAINT fk_asig_lic_licencia   FOREIGN KEY (id_licencia) REFERENCES licencia (id_licencia),
  CONSTRAINT fk_asig_lic_empleado   FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
  CONSTRAINT uq_asig_lic            UNIQUE (id_licencia, id_empleado)
);

-- ---------------------------------------------------------------------
-- TICKET
-- ---------------------------------------------------------------------
CREATE TABLE ticket (
  id_ticket      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_empleado    NUMBER         NOT NULL,
  id_tecnico     NUMBER,
  id_equipo      NUMBER,
  titulo         VARCHAR2(120)  NOT NULL,
  descripcion    VARCHAR2(2000) NOT NULL,
  categoria      VARCHAR2(15)   NOT NULL,
  prioridad      VARCHAR2(10)   DEFAULT 'MEDIA' NOT NULL,
  estado         VARCHAR2(12)   DEFAULT 'ABIERTO' NOT NULL,
  fecha_creacion DATE           DEFAULT SYSDATE NOT NULL,
  fecha_cierre   DATE,
  CONSTRAINT pk_ticket           PRIMARY KEY (id_ticket),
  CONSTRAINT fk_ticket_empleado  FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado),
  CONSTRAINT fk_ticket_tecnico   FOREIGN KEY (id_tecnico)  REFERENCES tecnico (id_tecnico),
  CONSTRAINT fk_ticket_equipo    FOREIGN KEY (id_equipo)   REFERENCES equipo (id_equipo),
  CONSTRAINT ck_ticket_categoria CHECK (categoria IN ('HARDWARE','SOFTWARE','RED','ACCESOS','OTRO')),
  CONSTRAINT ck_ticket_prioridad CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
  CONSTRAINT ck_ticket_estado    CHECK (estado IN ('ABIERTO','EN_PROCESO','RESUELTO','CERRADO')),
  CONSTRAINT ck_ticket_fechas    CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_creacion)
);

-- ---------------------------------------------------------------------
-- COMENTARIO_TICKET
-- ---------------------------------------------------------------------
CREATE TABLE comentario_ticket (
  id_comentario NUMBER GENERATED BY DEFAULT AS IDENTITY,
  id_ticket     NUMBER         NOT NULL,
  id_tecnico    NUMBER         NOT NULL,
  texto         VARCHAR2(1000) NOT NULL,
  fecha         DATE           DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_comentario_ticket PRIMARY KEY (id_comentario),
  CONSTRAINT fk_coment_ticket     FOREIGN KEY (id_ticket)  REFERENCES ticket (id_ticket) ON DELETE CASCADE,
  CONSTRAINT fk_coment_tecnico    FOREIGN KEY (id_tecnico) REFERENCES tecnico (id_tecnico)
);

-- ---------------------------------------------------------------------
-- ÍNDICES sobre llaves foráneas y columnas de filtro frecuentes
-- ---------------------------------------------------------------------
CREATE INDEX ix_empleado_depto      ON empleado (id_departamento);
CREATE INDEX ix_asig_eq_empleado    ON asignacion_equipo (id_empleado);
CREATE INDEX ix_asig_eq_equipo      ON asignacion_equipo (id_equipo);
CREATE INDEX ix_asig_lic_empleado   ON asignacion_licencia (id_empleado);
CREATE INDEX ix_licencia_venc       ON licencia (fecha_vencimiento);
CREATE INDEX ix_ticket_estado       ON ticket (estado);
CREATE INDEX ix_ticket_tecnico      ON ticket (id_tecnico);
CREATE INDEX ix_ticket_empleado     ON ticket (id_empleado);
CREATE INDEX ix_ticket_equipo       ON ticket (id_equipo);
CREATE INDEX ix_comentario_ticket   ON comentario_ticket (id_ticket);

