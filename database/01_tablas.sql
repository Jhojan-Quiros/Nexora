-- Limpieza para poder re-ejecutar el script
BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('COMENTARIO_TICKET','TICKET','ASIGNACION_LICENCIA',
                                  'ASIGNACION_EQUIPO','LICENCIA','EQUIPO','TECNICO',
                                  'EMPLEADO','DEPARTAMENTO')) LOOP
